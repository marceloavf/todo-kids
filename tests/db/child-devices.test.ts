import { expect, test } from 'vitest'
import { addChild, anonClient, familyWithTask, ok, sql } from './helpers.ts'

test('a paired device completes its own task and loses access when unlinked', async () => {
  const { f, child, task } = await familyWithTask({ points: 5 })
  const sibling = await addChild(f, 'Outro filho')
  const device = anonClient()
  const { data, error } = await device.auth.signInAnonymously()
  expect(error).toBeNull()
  const issue = async () => (await ok(f.client.rpc('issue_device_code', { p_token: f.token, p_child_id: child.id })))[0].code
  const redeem = (code: string) => ok(device.rpc('redeem_device_code', { p_code: code }))
  const expired = await issue()
  sql(`update private.device_codes set expires_at=now() where child_id='${child.id}'`)
  expect(await redeem(expired)).toBe('invalid')
  const replaced = await issue()
  const current = await issue()
  expect(await redeem(replaced)).toBe('invalid')
  expect(await redeem(current)).toBe('linked')
  expect(await ok(device.rpc('device_child_id'))).toBe(child.id)
  expect((await ok(device.from('profiles').select('id'))).map(p => p.id).sort()).toEqual([child.id, f.guardian.id].sort())
  expect((await ok(device.rpc('today_tasks'))).filter(row => row.task_id === task.id).map(row => row.child_id)).toEqual([child.id])
  expect((await device.rpc('complete_task', { p_child_id: sibling.id, p_task_id: task.id })).error?.message).toBe('not_authorized')
  await ok(device.rpc('complete_task', { p_child_id: child.id, p_task_id: task.id }))
  expect((await ok(device.from('profiles').select('balance').eq('id', child.id).single())).balance).toBe(5)
  const second = anonClient()
  expect((await second.auth.signInAnonymously()).error).toBeNull()
  expect(await ok(second.rpc('redeem_device_code', { p_code: current }))).toBe('invalid')
  expect(await ok(second.rpc('redeem_device_code', { p_code: await issue() }))).toBe('linked')
  await ok(f.client.rpc('revoke_child_device', { p_token: f.token, p_device_id: data.user!.id }))
  expect(await ok(device.from('profiles').select('id'))).toEqual([])
  expect(await ok(second.rpc('device_child_id'))).toBe(child.id)
  await ok(f.client.rpc('archive_profile', { p_token: f.token, p_id: child.id }))
  expect(await ok(second.from('profiles').select('id'))).toEqual([])
})
